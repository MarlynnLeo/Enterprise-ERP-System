export const getMenuLabel = (menu, t) => {
  const key = menu.path && pathToI18nKey[menu.path]
  if (key) return t(key)
  const permissionKey = menu.permission && permissionToI18nKey[menu.permission]
  return permissionKey ? t(permissionKey) : menu.name
}
