const toNumber = (value) => {
  const number = Number(value);
  return Number.isFinite(number) ? number : 0;
};

const dateOnly = (value) => {
  if (value) return String(value).slice(0, 10);
  return new Date().toISOString().slice(0, 10);
};

async function columnType(connection, tableName, columnName) {
  const [rows] = await connection.query(`SHOW COLUMNS FROM ${tableName} LIKE ?`, [columnName]);
  return rows[0]?.Type || '';
}

async function ensureQualityEnums(connection, counters) {
  const statusType = await columnType(connection, 'quality_inspections', 'status');
  if (!statusType.includes("'partial'") || !statusType.includes("'completed'")) {
    await connection.query(
      "ALTER TABLE quality_inspections MODIFY status ENUM('pending','in_progress','passed','failed','partial','conditional','completed') DEFAULT 'pending'"
    );
    counters.enumsUpdated += 1;
  }

  const typeType = await columnType(connection, 'inspection_templates', 'inspection_type');
  if (!typeType.includes("'first_article'")) {
    await connection.query(
      "ALTER TABLE inspection_templates MODIFY inspection_type ENUM('incoming','process','final','first_article') NOT NULL"
    );
    counters.enumsUpdated += 1;
  }
}

async function ensureDocumentLink(connection, sourceType, sourceId, sourceCode, targetType, targetId, targetCode) {
  if (!sourceId || !targetId) return false;
  const [existing] = await connection.query(
    `SELECT id FROM document_links
      WHERE source_type = ?
        AND source_id = ?
        AND target_type = ?
        AND target_id = ?
      LIMIT 1`,
    [sourceType, sourceId, targetType, targetId]
  );
  if (existing.length > 0) return false;

  await DocumentLinkService.tryAutoLink(
    sourceType,
    sourceId,
    sourceCode,
    targetType,
    targetId,
    targetCode,
    null,
    connection
  );
  return true;
}

async function repairDuplicateDocumentLinks(connection, counters) {
  const [result] = await connection.query(
    `DELETE dl
       FROM document_links dl
       JOIN document_links keep
         ON keep.source_type = dl.source_type
        AND keep.source_id = dl.source_id
        AND keep.target_type = dl.target_type
        AND keep.target_id = dl.target_id
        AND keep.id < dl.id`
  );
  counters.duplicateDocumentLinksRemoved += result.affectedRows || 0;
}

