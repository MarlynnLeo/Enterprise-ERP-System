async function ensurePurchaseOrderItem(connection, order, inspection, material) {
  const [existing] = await connection.query(
    'SELECT id, price, tax_rate, unit, unit_id FROM purchase_order_items WHERE order_id = ? AND material_id = ? LIMIT 1',
    [order.id, inspection.material_id]
  );
  if (existing.length > 0) return existing[0];

  const price = toNumber(material.price || material.cost_price);
  const quantity = toNumber(inspection.quantity || inspection.qualified_quantity);
  const taxRate = normalizeTaxRate(material.tax_rate, 0.13);
  const amount = lineAmount(quantity, price);
  const tax = calculateTaxAmount(amount, taxRate);
  const [result] = await connection.query(
    `INSERT INTO purchase_order_items
      (order_id, material_id, material_code, material_name, specification, unit, unit_id,
       price, quantity, received_quantity, warehoused_quantity, inspected_quantity,
       qualified_quantity, unqualified_quantity, total, tax_rate, amount_excluding_tax, tax_amount,
       created_at, updated_at)
     VALUES (?, ?, ?, ?, ?, ?, ?, ?, ?, 0, 0, ?, ?, ?, ?, ?, ?, ?, NOW(), NOW())`,
    [
      order.id,
      inspection.material_id,
      material.code,
      material.name,
      material.specs || '',
      material.unit_name || null,
      material.unit_id || null,
      price,
      quantity,
      quantity,
      toNumber(inspection.qualified_quantity),
      toNumber(inspection.unqualified_quantity),
      roundMoney(amount + tax),
      taxRate,
      amount,
      tax,
    ]
  );
  return {
    id: result.insertId,
    price,
    tax_rate: taxRate,
    unit: material.unit_name || null,
    unit_id: material.unit_id || null,
  };
}

async function ensureReceiptForInspection(connection, inspection, counters) {
  const [existing] = await connection.query(
    `SELECT id, receipt_no FROM purchase_receipts
      WHERE deleted_at IS NULL
        AND status <> 'cancelled'
        AND (inspection_id = ? OR receipt_no = ? OR order_no = ?)
      LIMIT 1`,
    [inspection.id, inspection.reference_no, inspection.reference_no]
  );
  if (existing.length > 0) return existing[0];

  const materialId = inspection.material_id || inspection.product_id;
  const [materials] = await connection.query(
    `SELECT m.*, u.name AS unit_name, l.name AS warehouse_name
       FROM materials m
       LEFT JOIN units u ON u.id = m.unit_id
       LEFT JOIN locations l ON l.id = m.location_id
      WHERE m.id = ? AND m.deleted_at IS NULL
      LIMIT 1`,
    [materialId]
  );
  if (materials.length === 0) return null;

  const material = materials[0];
  const order = await ensureHistoricalPurchaseOrder(connection, inspection, counters);
  const item = await ensurePurchaseOrderItem(connection, order, { ...inspection, material_id: materialId }, material);
  const quantity = toNumber(inspection.qualified_quantity);
  if (quantity <= 0) return null;

  const price = toNumber(item.price || material.price || material.cost_price);
  const taxRate = normalizeTaxRate(item.tax_rate || material.tax_rate, 0.13);
  const amount = lineAmount(quantity, price);
  const tax = calculateTaxAmount(amount, taxRate);
  const total = roundMoney(amount + tax);
  const receiptNo = await purchaseModel.generateReceiptNo(connection);
  const receiptDate = dateOnly(inspection.actual_date || inspection.planned_date || inspection.created_at);
  const fallbackSupplier = order.supplier_id ? null : await ensureHistoricalSupplier(connection);
  const supplierId = order.supplier_id || fallbackSupplier.id;
  const supplierName = order.supplier_name || fallbackSupplier.name;

  const [receipt] = await connection.query(
    `INSERT INTO purchase_receipts
      (receipt_no, order_id, order_no, supplier_id, supplier_name, warehouse_id, warehouse_name,
       receipt_date, operator, inspection_id, remarks, total_amount, total_tax_amount,
       from_inspection, status, created_at, updated_at)
     VALUES (?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, 1, 'draft', NOW(), NOW())`,
    [
      receiptNo,
      order.id,
      order.order_no,
      supplierId,
      supplierName,
      material.location_id || null,
      material.warehouse_name || null,
      receiptDate,
      inspection.inspector_name || 'system',
      inspection.id,
      `Historical receipt reconstructed from inspection ${inspection.inspection_no}`,
      total,
      tax,
    ]
  );

  await connection.query(
    `INSERT INTO purchase_receipt_items
      (receipt_id, order_item_id, material_id, material_code, material_name, specification, unit, unit_id,
       ordered_quantity, quantity, received_quantity, qualified_quantity, batch_number, price, tax_rate,
       amount_excluding_tax, tax_amount, total_amount, remarks, from_inspection, created_at, updated_at)
     VALUES (?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, 1, NOW(), NOW())`,
    [
      receipt.insertId,
      item.id,
      materialId,
      material.code,
      material.name,
      material.specs || '',
      item.unit || material.unit_name || null,
      item.unit_id || material.unit_id || null,
      toNumber(inspection.quantity || quantity),
      quantity,
      quantity,
      quantity,
      inspection.batch_no || '',
      price,
      taxRate,
      amount,
      tax,
      total,
      `Historical receipt item from inspection ${inspection.inspection_no}`,
    ]
  );

  await connection.query(
    `UPDATE quality_inspections
        SET reference_id = ?, reference_no = ?, updated_at = NOW()
      WHERE id = ?`,
    [order.id, order.order_no, inspection.id]
  );

  await ensureDocumentLink(
    connection,
    'quality_inspection',
    inspection.id,
    inspection.inspection_no,
    'purchase_receipt',
    receipt.insertId,
    receiptNo
  );

  counters.purchaseReceiptsCreated += 1;
  return { id: receipt.insertId, receipt_no: receiptNo };
}

